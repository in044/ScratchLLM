const musicalNotePattern = /^([A-G](?:2)?) (Bass|Elec Bass|Elec Guitar|Elec Piano|Guitar|Piano|Sax|Trombone|Trumpet)$/u;
const normalizedSoundJapaneseNames = Object.keys(soundJapaneseNames).reduce((names, name) => {
    names[name.toLocaleLowerCase()] = soundJapaneseNames[name];
    return names;
}, {});

export const getCostumeJapaneseName = name => (
    normalizedCostumeJapaneseNames[String(name || '').trim()
        .toLocaleLowerCase()] || ''
);

export const getSoundJapaneseName = name => {
    const englishName = String(name || '').trim();
    const translatedName = normalizedSoundJapaneseNames[englishName.toLocaleLowerCase()];
    if (translatedName) return translatedName;
    const musicalNote = englishName.match(musicalNotePattern);
    return musicalNote ? `${musicalNote[1]} ${instrumentNames[musicalNote[2]]}` : '';
};

export {costumeJapaneseNames, soundJapaneseNames};
