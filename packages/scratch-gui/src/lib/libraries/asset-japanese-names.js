// These names are intentionally maintained in source. The application never
// sends asset names to a translation service.
const unmatchedCostumeNames = {
    'Dragon1-a': 'ドラゴン1 1',
    'Dragon1-b': 'ドラゴン1 2',
    'Witch': '魔女'
};

const costumeOwnerByAssetId = new Map();
spriteLibraryContent.forEach(sprite => {
    const costumes = sprite.costumes || [];
    costumes.forEach((costume, index) => {
        if (!costume.assetId || !sprite.japaneseName) return;
        costumeOwnerByAssetId.set(costume.assetId, {
            index,
            japaneseName: sprite.japaneseName,
            total: costumes.length
        });
    });
});

const costumeJapaneseNames = costumeLibraryContent.reduce((names, costume) => {
    const owner = costumeOwnerByAssetId.get(costume.assetId);
    if (owner) {
        names[costume.name] = owner.total > 1 ?
            `${owner.japaneseName} ${owner.index + 1}` :
            owner.japaneseName;
    } else if (unmatchedCostumeNames[costume.name]) {
        names[costume.name] = unmatchedCostumeNames[costume.name];
    }
    return names;
}, {});
const normalizedCostumeJapaneseNames = Object.keys(costumeJapaneseNames).reduce((names, name) => {
    names[name.trim().toLocaleLowerCase()] = costumeJapaneseNames[name];
    return names;
}, {});

